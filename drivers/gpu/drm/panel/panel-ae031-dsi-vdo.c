static int ae031_get_modes(struct drm_panel *panel,
			   struct drm_connector *connector)
{
	unsigned int i;

	for (i = 0; i < ARRAY_SIZE(ae031_modes); i++) {
		struct drm_display_mode *mode;

		mode = drm_mode_duplicate(connector->dev, &ae031_modes[i]);
		if (!mode)
			return -ENOMEM;

		snprintf(mode->name, DRM_DISPLAY_MODE_LEN, "1280x2800@%u",
			 drm_mode_vrefresh(mode));
		drm_mode_probed_add(connector, mode);
	}

	return ARRAY_SIZE(ae031_modes);
}

